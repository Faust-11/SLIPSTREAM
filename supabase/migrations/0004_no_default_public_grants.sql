-- Нові об'єкти f1 не стають публічними автоматично.
-- 0001 видав anon/authenticated select «за замовчуванням» на всі майбутні таблиці й подання f1, а RLS і політики
-- ставив лише наявним таблицям. Нова таблиця без `enable row level security` або подання (RLS не має) одразу
-- читалися б через PostgREST із publishable-ключем — так 11.11 відкрився журнал міграцій (0003).
-- Відтепер кожна міграція видає select публічним об'єктам явно (як 0002 для team_index і site_meta).
-- Наявні права не змінюються. Перевірка — scripts/db/rls_smoke.py (структурні перевірки: RLS на кожній таблиці,
-- публічні подання й функції — лише зі списку).
-- Функції: execute для PUBLIC — глобальне правило Postgres, на рівні схеми його не відкликати; тому кожна
-- службова функція відкликає його сама (як f1.refresh_derived у 0002), а rls_smoke ловить пропуск.
alter default privileges in schema f1 revoke select on tables from anon, authenticated;
